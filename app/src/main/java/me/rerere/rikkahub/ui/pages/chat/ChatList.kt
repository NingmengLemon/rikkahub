/**
 * 上下文消息数上限的只读边界线。
 *
 * 位置是去掉最后一条助手回复后的 `contextLimitStart`，对应产生最后一条回复的请求（多步工具轮次可能差一个滞回步幅）；按滞回规则跳动，不落盘，关闭上限后消失。
 */
@Composable
private fun ContextLimitBoundary(limit: Int) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .padding(vertical = 4.dp),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(8.dp),
    ) {
        DashedLine(modifier = Modifier.weight(1f))
        Text(
            text = stringResource(R.string.chat_page_context_limit_boundary, limit),
            style = MaterialTheme.typography.labelSmall,
            color = MaterialTheme.colorScheme.onSurfaceVariant,
        )
        DashedLine(modifier = Modifier.weight(1f))
    }
}

@Composable
private fun DashedLine(modifier: Modifier = Modifier) {
    val color = MaterialTheme.colorScheme.outlineVariant
    val density = LocalDensity.current
    val pathEffect = remember(density) {
        PathEffect.dashPathEffect(
            floatArrayOf(
                with(density) { 6.dp.toPx() },
                with(density) { 4.dp.toPx() },
            )
        )
    }
    Canvas(modifier = modifier.height(1.dp)) {
        drawLine(
            color = color,
            start = Offset(0f, size.height / 2f),
            end = Offset(size.width, size.height / 2f),
            strokeWidth = 1.dp.toPx(),
            pathEffect = pathEffect,
        )
    }
}
